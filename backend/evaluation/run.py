class InputError(ValueError):
    """Malformed evaluation input; do not report it as a passing scenario."""


class UniqueLoader(yaml.SafeLoader):
    pass


def unique_mapping(loader, node, deep=False):
    result = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node, deep=deep)
        if key in result:
            raise InputError(f"duplicate YAML key {key!r} at line {key_node.start_mark.line + 1}")
        result[key] = loader.construct_object(value_node, deep=deep)
    return result


UniqueLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, unique_mapping)


def load_yaml(path: Path, model):
    try:
        return model.model_validate(yaml.load(path.read_text(encoding="utf-8"), UniqueLoader))
    except (ValueError, TypeError, yaml.YAMLError) as exc:
        raise InputError(f"{path.name}: {exc}") from exc


def identity(kind: str, alias: str) -> UUID:
    return uuid5(NAMESPACE_URL, f"cookish/evaluation/development/{kind}/{alias}")


@dataclass
class World:
    fixtures: Fixtures
    recipes: dict[str, Candidate]
    catalogue: dict[UUID, CatalogIngredient]


def make_world(fixtures: Fixtures) -> World:
    if not fixtures.ingredients or not fixtures.recipes:
        raise InputError("fixtures must contain ingredients and recipes")
    catalogue = {
        identity("ingredient", name): CatalogIngredient(
            id=identity("ingredient", name),
            canonical_name=name,
            **spec.model_dump(exclude={"purchase"}),
        )
        for name, spec in fixtures.ingredients.items()
    }
    recipes = {}
    for alias, spec in fixtures.recipes.items():
        base = spec.base_recipe
        if base and (base not in fixtures.recipes or fixtures.recipes[base].base_recipe):
            raise InputError(f"{alias}: base_recipe must refer to a base fixture")
        if base == alias:
            raise InputError(f"{alias}: recipe cannot be its own base")
        lines = []
        for line in spec.ingredients:
            if line.ingredient not in fixtures.ingredients:
                raise InputError(f"{alias}: unknown ingredient {line.ingredient}")
            lines.append(
                RecipeIngredient(
                    ingredient_id=identity("ingredient", line.ingredient),
                    name=line.ingredient,
                    prep_note=None,
                    **line.model_dump(exclude={"ingredient"}),
                )
            )
        recipes[alias] = Candidate(
            id=identity("recipe", alias),
            title=spec.title or alias,
            base_recipe_id=identity("recipe", base) if base else None,
            variant_label=alias if base else None,
            active_minutes=spec.total_minutes,
            ingredients=lines,
            steps=["Synthetic evaluation fixture; not a cooking recipe."],
            **spec.model_dump(exclude={"title", "base_recipe", "ingredients"}),
        )
    return World(fixtures, recipes, catalogue)


def validate_references(case: Scenario, world: World):
    expected_prefix = "DEV-C" if case.mode == "cook" else "DEV-S"
    if not case.id.startswith(expected_prefix):
        raise InputError(f"{case.id}: ID prefix does not match mode")
    unknown = set(case.recipes) - world.recipes.keys()
    if unknown:
        raise InputError(f"{case.id}: unknown recipes {sorted(unknown)}")
    batches = [(batch.ingredient, batch.key) for batch in case.inventory]
    if len(set(batches)) != len(batches):
        raise InputError(f"{case.id}: duplicate inventory batch key")
    ingredients = set(case.preferences.disliked_ingredients) | {name for name, _ in batches}
    for expected in [case.expect, *(step.expect for step in case.adjustments)]:
        recipes = [*expected.selected_any, *(expected.planned or [])]
        if set(recipes) - set(case.recipes) or len(recipes) != len(set(recipes)):
            raise InputError(f"{case.id}: expected recipes must be unique scenario candidates")
        ingredients.update(expected.ingredient_status)
        ingredients.update(expected.amounts)
        ingredients.update(expected.needs_check or [])
        ingredients.update(expected.freshness_check or [])
        ingredients.update(expected.items or {})
    unknown = ingredients - world.fixtures.ingredients.keys()
    if unknown:
        raise InputError(f"{case.id}: unknown ingredients {sorted(unknown)}")


def inputs(case: Scenario, world: World):
    now = world.fixtures.as_of
    prefs = Preferences(
        **case.preferences.model_dump(exclude={"disliked_ingredients"}),
        disliked_ingredient_ids=[
            identity("ingredient", name) for name in case.preferences.disliked_ingredients
        ],
        updated_at=now,
    )
    inventory = []
    for batch in case.inventory:
        spec = world.fixtures.ingredients[batch.ingredient]
        inventory.append(
            InventoryItem(
                id=identity("batch", f"{case.id}/{batch.ingredient}/{batch.key}"),
                ingredient_id=identity("ingredient", batch.ingredient),
                display_name=batch.ingredient,
                category=spec.purchase.category,
                countable=spec.countable,
                count=batch.count,
                unit=batch.unit,
                remaining_state=batch.remaining_state,
                storage=Storage.FRIDGE,
                source=ItemSource.MANUAL,
                acquired_at=(now - timedelta(days=batch.acquired_days_ago)).date(),
                label_date=None,
                label_date_kind=None,
                est_use_first_date=(now + timedelta(days=batch.use_first_in_days)).date()
                if batch.use_first_in_days is not None
                else None,
                freshness_status=batch.freshness_status,
                freshness_confirmed_at=None,
                last_confirmed_at=now - timedelta(days=batch.confirmed_days_ago),
                revision=1,
            )
        )
    return prefs, inventory


def hard_violations(recipe: Candidate, prefs: Preferences, strict_minutes, catalogue) -> list[str]:
    """Independent output oracle: deliberately does not call the engine's filter."""
    failures = []
    if not recipe.reviewed:
        failures.append("unreviewed recipe")
    if set(recipe.equipment) - set(prefs.equipment):
        failures.append("unavailable equipment")
    if strict_minutes is not None and recipe.total_minutes > strict_minutes:
        failures.append("strict time bound exceeded")
    for line in recipe.ingredients:  # Optional ingredients are checked too.
        meta = catalogue.get(line.ingredient_id)
        if meta is None or meta.id != line.ingredient_id:
            failures.append(f"{line.name}: missing/mismatched metadata")
        else:
            if set(prefs.allergens) & meta.allergens:
                failures.append(f"{line.name}: excluded allergen")
            if set(prefs.diets) - meta.diet_flags:
                failures.append(f"{line.name}: incompatible diet")
    return failures


def contains_amount_fragment(amount: str, fragment: str) -> bool:
    # A quantity must not match inside another number, fraction or unit token.
    return re.search(r"(?<![\w.,/+\-])" + re.escape(fragment) + r"(?![\w/])", amount) is not None


def run_scenario(case: Scenario, world: World) -> dict:
    validate_references(case, world)
    prefs, inventory = inputs(case, world)
    candidates = [world.recipes[name] for name in case.recipes]
    names = {recipe.id: name for name, recipe in world.recipes.items()}
    purchases = {
        identity("ingredient", name): spec.purchase
        for name, spec in world.fixtures.ingredients.items()
    }
    cook = case.mode == "cook"
    session = (
        new_session(prefs, case.request.people, strict_max_minutes=case.request.strict_max_minutes)
        if cook
        else new_shop_session(
            prefs,
            case.request.people,
            case.request.meals,
            strict_max_minutes=case.request.strict_max_minutes,
        )
    )
    steps, previous = [], None
    expectations = [case.expect, *(step.expect for step in case.adjustments)]
    for index, expected in enumerate(expectations):
        failures, observed = [], {}

        def fail(message, kind="expectation", target=failures):
            target.append({"kind": kind, "message": message})

        def equal(label, actual, wanted):
            if actual != wanted:
                fail(f"{label}: expected {wanted!r}, got {actual!r}")

        try:
            if index:
                patch = case.adjustments[index - 1].patch
                if cook:
                    if previous is None or previous.selected is None:
                        raise ValueError("Cook adjustment needs a preceding selected recipe")
                    session = adjust(
                        session, CookAdjust.model_validate(patch), previous.selected.recipe
                    )
                else:
                    session = adjust_shop(session, ShopAdjust.model_validate(patch))
            common = dict(as_of=world.fixtures.as_of, taste_weights=case.taste_weights)
            result = (
                suggest(candidates, inventory, prefs, session, world.catalogue, **common)
                if cook
                else plan_shop(
                    candidates,
                    inventory,
                    prefs,
                    session,
                    world.catalogue,
                    purchases,
                    **common,
                )
            )
            session, previous = result.session, result
            chosen = (
                ([result.selected.recipe] if result.selected else [])
                if cook
                else list(result.planned_meals)
            )
            observed["result"] = bool(chosen)
            equal("result", bool(chosen), expected.result)
            for recipe in chosen:
                if recipe.id not in {candidate.id for candidate in candidates}:
                    fail("output recipe outside scenario candidate pool", "hard_constraint")
                for violation in hard_violations(
                    recipe,
                    prefs,
                    case.request.strict_max_minutes,
                    world.catalogue,
                ):
                    fail(violation, "hard_constraint")
            if cook:
                observed.update(
                    selected=names.get(chosen[0].id) if chosen else None,
                    relaxable=list(result.relaxable),
                    missing_essential_fallback=result.missing_essential_fallback,
                )
                if expected.relaxable is not None:
                    equal("relaxable", sorted(result.relaxable), sorted(expected.relaxable))
                if expected.missing_essential_fallback is not None:
                    equal(
                        "missing fallback",
                        result.missing_essential_fallback,
                        expected.missing_essential_fallback,
                    )
                if chosen:
                    recipe = chosen[0]
                    if names.get(recipe.id) not in expected.selected_any:
                        fail(
                            f"selected {names.get(recipe.id)!r}, expected {expected.selected_any!r}"
                        )
                    if (
                        session.max_minutes is not None
                        and recipe.total_minutes > session.max_minutes
                    ):
                        fail("accumulated time bound exceeded", "constraint")
                    if (
                        session.max_difficulty is not None
                        and recipe.difficulty > session.max_difficulty
                    ):
                        fail("accumulated difficulty bound exceeded", "constraint")
                    if session.required_tags - set(recipe.taste_tags):
                        fail("accumulated required tags missing", "constraint")
                    public = to_suggestion(result, identity("session", case.id))
                    observed.update(
                        people=public.people,
                        ingredient_status={
                            item.name: item.status.value for item in public.ingredients
                        },
                        amounts={item.name: item.amount for item in public.ingredients},
                        needs_check=sorted(item.item.display_name for item in public.needs_check),
                        freshness_check=sorted(
                            item.item.display_name for item in public.freshness_check
                        ),
                    )
                    for name, status in expected.ingredient_status.items():
                        equal(
                            f"{name} status", observed["ingredient_status"].get(name), status.value
                        )
                    for name, amount in expected.amounts.items():
                        equal(f"{name} amount", observed["amounts"].get(name), amount)
                    for key in ("needs_check", "freshness_check"):
                        if getattr(expected, key) is not None:
                            equal(key, observed[key], sorted(getattr(expected, key)))
            else:
                observed.update(
                    meal_count=len(chosen), planned=sorted(names.get(r.id) for r in chosen)
                )
                equal("meal_count", len(chosen), expected.meal_count)
                if expected.planned is not None:
                    equal("planned", observed["planned"], sorted(expected.planned))
                families = [recipe.base_recipe_id or recipe.id for recipe in chosen]
                if len(set(families)) != len(families) or len(chosen) > session.meals:
                    fail("duplicate family or too many planned meals", "constraint")
                actual_items = {}
                if chosen:
                    public = to_basket(
                        result, identity("session", case.id), identity("basket", case.id)
                    )
                    actual_items = {item.name: item for item in public.items}
                    if len(actual_items) != len(public.items):
                        fail("duplicate basket ingredient", "constraint")
                equal("basket ingredients", sorted(actual_items), sorted(expected.items))
                observed["items"] = {
                    name: {
                        "packs": item.suggested_packs,
                        "needs_check": item.needs_check,
                        "amount": item.amount,
                    }
                    for name, item in actual_items.items()
                }
                for name, wanted in expected.items.items():
                    if name in actual_items:
                        item = actual_items[name]
                        equal(f"{name} packs", item.suggested_packs, wanted.packs)
                        equal(f"{name} check", item.needs_check, wanted.needs_check)
                        if wanted.amount_contains is not None and not contains_amount_fragment(
                            item.amount, wanted.amount_contains
                        ):
                            fail(
                                f"{name} amount: missing {wanted.amount_contains!r} "
                                f"in {item.amount!r}"
                            )
        except Exception as exc:
            fail(f"{type(exc).__name__}: {exc}", "runtime")
        steps.append(
            {"step": index, "passed": not failures, "observed": observed, "failures": failures}
        )
        if any(failure["kind"] == "runtime" for failure in failures):
            break
    return {
        "id": case.id,
        "mode": case.mode,
        "description": case.description,
        "categories": case.categories,
        "passed": all(step["passed"] for step in steps),
        "steps": steps,
    }


def digest(path: Path) -> str:
    # Normalize line endings so provenance is stable on Windows and Linux checkouts.
    return hashlib.sha256(path.read_text(encoding="utf-8").encode()).hexdigest()


def git_value(*args):
    result = subprocess.run(
        ["git", "-c", f"safe.directory={ROOT.as_posix()}", *args],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    return result.stdout.strip() if result.returncode == 0 else None


def run_suite(fixtures_path=SUITE / "fixtures.yaml", cases_dir=SUITE / "development", selected=()):
    fixtures_path, cases_dir = Path(fixtures_path), Path(cases_dir)
    world = make_world(load_yaml(fixtures_path, Fixtures))
    paths = sorted(cases_dir.glob("*.yaml"))
    cases = [load_yaml(path, Scenario) for path in paths]
    ids = [case.id for case in cases]
    if len(set(ids)) != len(ids):
        raise InputError("duplicate scenario IDs")
    for case in cases:
        validate_references(case, world)
    wanted = {*(f"DEV-C{i:02}" for i in range(1, 41)), *(f"DEV-S{i:02}" for i in range(1, 31))}
    if not selected and set(ids) != wanted:
        raise InputError(
            f"full development suite must contain exactly 40 Cook + 30 Shop cases; got {len(ids)}"
        )
    if set(selected) - set(ids):
        raise InputError(f"unknown selected IDs: {sorted(set(selected) - set(ids))}")
    results = [run_scenario(case, world) for case in cases if not selected or case.id in selected]
    steps = [step for result in results for step in result["steps"]]
    categories = {}
    for name in sorted({name for result in results for name in result["categories"]}):
        members = [result for result in results if name in result["categories"]]
        categories[name] = {"scenarios": len(members), "passed": sum(r["passed"] for r in members)}
    source_paths = sorted((ROOT / "backend/app/reco").glob("*.py"))
    source_paths += sorted((ROOT / "backend/app/schemas").glob("*.py"))
    source_paths += sorted((ROOT / "backend/evaluation").glob("*.py"))
    source_paths += [ROOT / "backend/app/clock.py"]
    source_paths += [ROOT / "backend/pyproject.toml", ROOT / "backend/uv.lock"]
    status = git_value("status", "--porcelain")
    return {
        "version": 1,
        "split": "development",
        "selection": list(selected) or "full",
        "scope": (
            "Offline synthetic fixtures; not held-out, database, deployed, "
            "load or user-study evidence."
        ),
        "as_of": world.fixtures.as_of.isoformat(),
        "summary": {
            "scenarios": len(results),
            "passed": sum(r["passed"] for r in results),
            "steps": len(steps),
            "steps_passed": sum(step["passed"] for step in steps),
            "failures_by_kind": dict(Counter(f["kind"] for s in steps for f in s["failures"])),
            "modes": dict(Counter(result["mode"] for result in results)),
            "held_out_executed": 0,
        },
        "provenance": {
            "git_head": git_value("rev-parse", "HEAD"),
            "working_tree_dirty": None if status is None else bool(status),
            "runtime": {
                "python": platform.python_version(),
                "pydantic": pydantic_version,
                "pyyaml": yaml.__version__,
            },
            "source_sha256": {p.relative_to(ROOT).as_posix(): digest(p) for p in source_paths},
            "fixture_sha256": digest(fixtures_path),
            "scenario_sha256": {path.name: digest(path) for path in paths},
            "config": {
                "cook": asdict(DEFAULT_CONFIG),
                "shop": asdict(DEFAULT_SHOP_CONFIG),
                "learning": asdict(DEFAULT_LEARNING_CONFIG),
            },
        },
        "categories": categories,
        "results": results,
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixtures", type=Path, default=SUITE / "fixtures.yaml")
    parser.add_argument("--cases-dir", type=Path, default=SUITE / "development")
    parser.add_argument(
        "--case", action="append", default=[], help="Run selected development IDs only"
    )
    parser.add_argument(
        "--output", type=Path, help="Write a JSON report (development outputs only)"
    )
    args = parser.parse_args(argv)
    try:
        report = run_suite(args.fixtures, args.cases_dir, args.case)
    except (InputError, ValueError, OSError) as exc:
        print(f"Invalid evaluation input: {exc}", file=sys.stderr)
        return 2
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(
            json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
    summary = report["summary"]
    print(
        f"Development: {summary['passed']}/{summary['scenarios']} scenarios; "
        f"{summary['steps_passed']}/{summary['steps']} steps passed; held-out executed: 0"
    )
    for result in report["results"]:
        for step in result["steps"]:
            for failure in step["failures"]:
                print(
                    f"{result['id']} step {step['step']} [{failure['kind']}]: {failure['message']}"
                )
    return 0 if summary["passed"] == summary["scenarios"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
